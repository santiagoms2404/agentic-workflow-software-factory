export const META = "core/test/unit/meta";
export type ScanRoot = string | { readonly prefix: string; readonly extensions: readonly string[] };
const source = (prefix: string): ScanRoot => ({ prefix, extensions: CODE_EXTS });
const markdown = (prefix: string): ScanRoot => ({ prefix, extensions: [".md"] });

export interface Fence {
  readonly rule: string;
  // Areas name content readers, not fences that only read Git pathnames.
  readonly areas: readonly Area[];
  // Required inputs narrower than an area, or inputs that are not code.
  // A trailing slash means a subtree; other strings are exact paths.
  readonly roots: readonly ScanRoot[];
  readonly plants: readonly string[];
}

type Registration = { readonly fences: readonly Fence[] } | { readonly reason: string };
const fence = (rule: string, areas: readonly Area[], roots: readonly ScanRoot[], ...plants: string[]): Registration =>
  ({ fences: [{ rule, areas, roots, plants }] });
const notFence = (reason: string): Registration => ({ reason });
